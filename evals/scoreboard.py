"""Generate `evals/scoreboard.md` and the scoreboard block in `README.md` from the results.

    python -m evals.scoreboard
    python -m evals.scoreboard --check

The scoreboard is the point of the project, so it is generated and never typed. Every number in
it is recomputed here from the per-question rows of the latest results file of each
configuration, which means a number can always be traced to the run, the commit and the
questions behind it, and a hand edit is caught by `--check` in CI.

A cell with no measurement behind it renders as a dash. A dash is the absence of a measurement,
never a stand-in value: the headline columns are fixed for the whole series, so most of them
stay empty until the part that fills them.
"""

import argparse
import sys
from collections.abc import Callable, Mapping, Sequence
from datetime import UTC, datetime
from pathlib import Path

from evals import metrics
from evals.golden import DEFAULT_GOLDEN_SET, GoldenItem, GoldenSetError, load_golden_set
from evals.metrics import NOT_MEASURED, Aggregates
from evals.results import (
    REPO_ROOT,
    RESULTS_DIR,
    QuestionResult,
    ResultsError,
    RetrievedChunk,
    RunResult,
    latest_per_config,
)

SCOREBOARD_PATH = REPO_ROOT / "evals" / "scoreboard.md"
README_PATH = REPO_ROOT / "README.md"

BLOCK_START = "<!-- scoreboard:start -->"
BLOCK_END = "<!-- scoreboard:end -->"

# The line `--check` ignores, because it changes on every run without any number changing.
GENERATED_PREFIX = "Generated at "

# The columns are fixed for the whole series: the same table closes every part with more cells
# filled in. The part that fills each one is named in the legend under the table.
HEADLINE_COLUMNS = (
    "Configuration",
    "Page hit@5",
    "Manual pass",
    "Context recall",
    "Context precision",
    "Faithfulness",
    "Answer relevance",
    "Cost per query",
    "p95 latency",
    "Judge pass",
    "Adversarial pass",
)
LEGEND = (
    f"`{NOT_MEASURED}` means not measured yet, never a stand-in value. Part 1 fills Page hit@5 "
    "and Manual pass; part 2 the four RAGAS columns; part 3 cost per query and p95 latency; "
    "part 4 the judge and adversarial columns. The four RAGAS columns are scored by the judge "
    "model named in the provenance table and are LLM-judged estimates."
)

# The order part 1 and part 2's configurations appear in. Anything else follows, alphabetically.
CONFIG_ORDER = (
    "hybrid",
    "hybrid+rerank",
    "sections",
    "sections+rerank",
    "vector-only",
    "lexical-only",
)

# Retrieval metrics only apply to questions the handbook answers, so the breakdown by question
# type has a column per answerable type.
ANSWERABLE_TYPES = ("lookup", "table", "multi_section")

# The cut every configuration returns to the caller, the same "5" as `page_hit@5`. The
# re-ranker movement table classifies a question's first covering chunk by whether its
# pre-re-rank `fused_rank` already sat inside this cut.
RERANK_TOP_K = 5

NO_RUNS = "No eval has been run yet, so the table has no rows."
COMMIT_LENGTH = 7
HASH_LENGTH = 12

EXIT_OK = 0
EXIT_STALE = 1
EXIT_ERROR = 2


class ScoreboardError(RuntimeError):
    """Raised when the scoreboard cannot be written, as opposed to being out of date."""


def now_stamp() -> str:
    """The generation time, to the minute, in UTC."""
    return datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")


def render(
    results: Mapping[str, RunResult],
    generated_at: str,
    golden: Mapping[str, GoldenItem] | None = None,
) -> str:
    """The whole of `evals/scoreboard.md`.

    `golden` is the golden set keyed by id, needed only by the re-ranker movement table. Leave
    it out to have that table load the committed golden set itself, lazily, and only when some
    row actually has a re-ranker; a test passes a small one of its own instead.
    """
    lines = [
        "# Scoreboard",
        "",
        "<!-- Generated by `python -m evals.scoreboard` from the results files in evals/results/.",
        "     Never edit this file by hand: change the results or the generator and run it "
        "again. -->",
        "",
        *_header_lines(results, generated_at),
        "",
        *_table(HEADLINE_COLUMNS, _headline_rows(results)),
        "",
        LEGEND,
    ]
    if results:
        lines += ["", *_detail_section(results, golden)]
    return "\n".join(lines) + "\n"


def render_readme_block(results: Mapping[str, RunResult], generated_at: str) -> str:
    """What goes between the scoreboard markers in `README.md`: the headline table only."""
    lines = [
        BLOCK_START,
        "<!-- Generated by `python -m evals.scoreboard`. Never edit this block by hand. -->",
        "",
        *_header_lines(results, generated_at),
        "",
        *_table(HEADLINE_COLUMNS, _headline_rows(results)),
        "",
        LEGEND,
    ]
    if results:
        lines += [
            "",
            "The secondary metrics and the breakdown by question type are in "
            "[evals/scoreboard.md](evals/scoreboard.md).",
        ]
    lines.append(BLOCK_END)
    return "\n".join(lines)


def _header_lines(results: Mapping[str, RunResult], generated_at: str) -> list[str]:
    """What every reader needs before the numbers: which corpus, which golden set, when."""
    if not results:
        return [NO_RUNS, "", f"{GENERATED_PREFIX}{generated_at}."]
    newest = max(results.values(), key=lambda result: (result.created_at, result.run_id))
    corpus = newest.corpus
    header = [
        f"Golden set: {newest.golden_set.count} questions · Corpus: Medicare & You, "
        f"{corpus.edition} edition, sha256 `{corpus.sha256[:HASH_LENGTH]}`",
    ]
    if _disagree(results):
        header.append("")
        header.append(
            "Not every row ran against the same corpus or the same golden set, so the rows are "
            "not strictly comparable. Re-run the older configurations."
        )
    header += ["", f"{GENERATED_PREFIX}{generated_at}."]
    return header


def _disagree(results: Mapping[str, RunResult]) -> bool:
    """True when the rows did not all run against the same corpus and golden set."""
    pinned = {(result.corpus.sha256, result.golden_set.sha256) for result in results.values()}
    return len(pinned) > 1


def _headline_rows(results: Mapping[str, RunResult]) -> list[list[str]]:
    """One row per configuration: part 1's two columns, part 2's four, a dash for the rest."""
    rows = []
    for name, result in _ordered(results):
        totals = result.aggregates
        rows.append(
            [
                name,
                metrics.as_percentage(totals.page_hit),
                _manual_pass(totals),
                metrics.as_score(totals.context_recall),
                metrics.as_score(totals.context_precision),
                metrics.as_score(totals.faithfulness),
                metrics.as_score(totals.answer_relevance),
                *[NOT_MEASURED] * (len(HEADLINE_COLUMNS) - 7),
            ]
        )
    return rows


def _manual_pass(totals: Aggregates) -> str:
    """The pass rate with the number of answers a person actually looked at."""
    if totals.manual.reviewed == 0:
        return NOT_MEASURED
    return f"{metrics.as_percentage(totals.manual.rate)} ({totals.manual.reviewed} reviewed)"


MOVEMENT_COLUMNS = (
    "Configuration",
    "Lifted into the top 5",
    "Already in the top 5",
    "No expected page in the top 5",
    "Answerable questions",
)

MOVEMENT_NOTE = (
    "Only rows with a re-ranker are in this table. It is computed from the top 5 each run "
    "stored, checked against the golden set as it stands now, `alt_pages` included. For each "
    "answerable question it takes the first stored chunk covering an expected page or one of "
    "its `alt_pages` alternates: `fused_rank` > 5 means that chunk sat outside the top 5 before "
    "re-ranking and re-ranking lifted it in; `fused_rank` ≤ 5 means it was already there. "
    "*Lifted* counts that chunk, not its page: another chunk of the same page may already have "
    "been in the top 5 before re-ranking, so this column can be larger than the number of "
    "questions whose page the re-ranker newly brought into the top 5, which is what the rise in "
    "`page_hit@5` over the row's un-re-ranked twin (`hybrid` or `sections`) shows. A page the "
    "re-ranker pushed *out* of the top 5 cannot be seen from the stored top 5, so it never "
    "appears here — that loss is what a lower `page_hit@5` on this row than on its twin shows."
)

PROVENANCE_COLUMNS = (
    "Configuration",
    "Mode",
    "Chunk set",
    "k",
    "Candidates",
    "RRF k",
    "Reranker",
    "Embedding model",
    "Answer model",
    "Judge model",
    "Commit",
    "Run",
)


def _detail_section(
    results: Mapping[str, RunResult], golden: Mapping[str, GoldenItem] | None = None
) -> list[str]:
    """The detail behind the headline: secondary metrics, breakdowns by type, the re-ranker's
    effect, and where every row came from."""
    lines = [
        "## Detail",
        "",
        "### Secondary metrics",
        "",
        *_table(
            (
                "Configuration",
                "page_recall@5",
                "mrr",
                "cited_page_hit",
                "abstention_accuracy",
                "Answers reviewed",
            ),
            _secondary_rows(results),
        ),
        "",
        "`page_recall@5` is the share of a question's expected pages that were found, so it is "
        "the column that exposes questions whose answer needs two sections.",
        "",
        "### page_hit@5 by question type",
        "",
        *_table(
            ("Configuration", *ANSWERABLE_TYPES),
            _type_rows(results, "page_hit", metrics.as_percentage),
        ),
        "",
        "Each cell is the share of that type's questions whose expected page was retrieved, "
        "with the number of questions of that type in brackets. Unanswerable questions have no "
        "expected pages, so they are not in this table; what they measure is "
        "`abstention_accuracy` above.",
        "",
        "### page_recall@5 by question type",
        "",
        *_table(
            ("Configuration", *ANSWERABLE_TYPES),
            _type_rows(results, "page_recall", metrics.as_percentage),
        ),
        "",
        "Each cell is the mean share of that type's questions' expected pages that were found, "
        "with the number of questions of that type in brackets.",
        "",
        "### context_recall by question type",
        "",
        *_table(
            ("Configuration", *ANSWERABLE_TYPES),
            _type_rows(results, "context_recall", metrics.as_score),
        ),
        "",
        "Each cell is the mean share of the expected answer's sentences the retrieved passages "
        "supported, for that type's questions a scoring pass has scored, with that count in "
        "brackets.",
        "",
        "### faithfulness by question type",
        "",
        *_table(
            ("Configuration", *ANSWERABLE_TYPES),
            _type_rows(results, "faithfulness", metrics.as_score),
        ),
        "",
        "Each cell is the mean share of the generated answer's own claims the retrieved "
        "passages supported, for that type's questions with at least one claim to check, with "
        "that count in brackets.",
    ]
    movement = _movement_rows(results, golden)
    if movement:
        lines += [
            "",
            "### Re-ranker movement",
            "",
            *_table(MOVEMENT_COLUMNS, movement),
            "",
            MOVEMENT_NOTE,
        ]
    lines += [
        "",
        "### What produced each row",
        "",
        *_table(PROVENANCE_COLUMNS, _run_rows(results)),
    ]
    failures = _failure_lines(results)
    if failures:
        lines += ["", *failures]
    return lines


def _secondary_rows(results: Mapping[str, RunResult]) -> list[list[str]]:
    """The metrics that explain the headline but are not part of the series' fixed columns."""
    rows = []
    for name, result in _ordered(results):
        totals = result.aggregates
        reviewed = (
            f"{totals.manual.reviewed} of {totals.answered}" if totals.answered else NOT_MEASURED
        )
        rows.append(
            [
                name,
                metrics.as_percentage(totals.page_recall),
                metrics.as_score(totals.mrr),
                metrics.as_percentage(totals.cited_page_hit),
                metrics.as_percentage(totals.abstention_accuracy),
                reviewed,
            ]
        )
    return rows


def _type_rows(
    results: Mapping[str, RunResult], metric_name: str, render_value: Callable[[float], str]
) -> list[list[str]]:
    """One `QuestionMetrics` field broken down by question type, in the shape of the
    `page_hit@5` table: which kind of question a metric is weak on.

    `render_value` formats the type's mean the same way the headline table does for that
    metric — a percentage for the part 1 metrics, two decimals for the RAGAS ones. A type with
    no scored question of that kind in this run is a dash, never a zero.
    """
    rows = []
    for name, result in _ordered(results):
        cells = [name]
        for question_type in ANSWERABLE_TYPES:
            scored = [
                getattr(row.metrics, metric_name)
                for row in result.questions
                if row.type == question_type and getattr(row.metrics, metric_name) is not None
            ]
            cells.append(
                NOT_MEASURED
                if not scored
                else f"{render_value(metrics.mean(scored))} ({len(scored)})"
            )
        rows.append(cells)
    return rows


def _movement_rows(
    results: Mapping[str, RunResult], golden: Mapping[str, GoldenItem] | None
) -> list[list[str]]:
    """One row per re-ranked configuration: how many answerable questions the re-ranker lifted
    into the top 5, left there already, or could not find an expected page for at all.

    Configurations with no re-ranker (`config.reranker` is `None`) are left out entirely, so
    this is `[]` — and the whole table is omitted — until a re-ranked row exists. The golden set
    is loaded lazily, only once that happens, so an ordinary scoreboard run never touches it.
    """
    reranked = [(name, result) for name, result in _ordered(results) if result.config.reranker]
    if not reranked:
        return []
    items = golden if golden is not None else _golden_by_id()

    rows = []
    for name, result in reranked:
        lifted = already = missing = 0
        for question in result.questions:
            if not question.answerable:
                continue
            chunk = _first_covering_chunk(question, items.get(question.id))
            if chunk is None:
                missing += 1
            elif chunk.fused_rank is not None and chunk.fused_rank > RERANK_TOP_K:
                lifted += 1
            else:
                already += 1
        rows.append(
            [name, str(lifted), str(already), str(missing), str(lifted + already + missing)]
        )
    return rows


def _first_covering_chunk(
    question: QuestionResult, item: GoldenItem | None
) -> RetrievedChunk | None:
    """The lowest-rank stored chunk covering an expected page or one of its alternates.

    The same rule `metrics.found_expected_pages` uses to decide a page was found at all, applied
    to the stored top-k rather than the full candidate pool. Falls back to the question's own
    `expected_pages`, with no alternates, when the golden item cannot be found, rather than
    failing the whole row over one missing id.
    """
    satisfying_pages = _satisfying_pages(question, item)
    covering = [
        chunk
        for chunk in question.retrieved
        if any(metrics.covers(chunk, page) for page in satisfying_pages)
    ]
    return min(covering, key=lambda chunk: chunk.rank, default=None)


def _satisfying_pages(question: QuestionResult, item: GoldenItem | None) -> set[int]:
    """Every page that counts as satisfying one of this question's expected pages."""
    if item is None:
        return set(question.expected_pages)
    return {
        page for expected in question.expected_pages for page in item.pages_that_satisfy(expected)
    }


def _golden_by_id() -> dict[str, GoldenItem]:
    """The committed golden set, keyed by id — read only for the re-ranker movement table."""
    return {item.id: item for item in load_golden_set(DEFAULT_GOLDEN_SET)}


def _run_rows(results: Mapping[str, RunResult]) -> list[list[str]]:
    """Where each row came from: the configuration, the models involved, the commit, and the
    results file."""
    rows = []
    for name, result in _ordered(results):
        config = result.config
        commit = result.git.commit[:COMMIT_LENGTH] if result.git.commit else NOT_MEASURED
        judge_model = result.scoring.judge_model if result.scoring else NOT_MEASURED
        rows.append(
            [
                name,
                config.mode,
                config.chunk_set,
                str(config.top_k),
                str(config.candidates),
                str(config.rrf_k),
                config.reranker or NOT_MEASURED,
                config.embedding_model,
                config.llm_model or NOT_MEASURED,
                judge_model,
                f"{commit} (dirty)" if result.git.dirty else commit,
                result.run_id,
            ]
        )
    return rows


def _failure_lines(results: Mapping[str, RunResult]) -> list[str]:
    """Name any configuration whose run had questions fail, so no number hides a gap."""
    lines = []
    for name, result in _ordered(results):
        failed = len(result.errors)
        if failed:
            noun = "question" if failed == 1 else "questions"
            lines.append(
                f"`{name}`: {failed} {noun} failed during the run and scored nothing. The error "
                f"is recorded in `evals/results/{result.run_id}.json`."
            )
    return lines


def _ordered(results: Mapping[str, RunResult]) -> list[tuple[str, RunResult]]:
    """Part 1's configurations first, in the order the spec names them, then the rest."""
    known = [(name, results[name]) for name in CONFIG_ORDER if name in results]
    rest = sorted((name, result) for name, result in results.items() if name not in CONFIG_ORDER)
    return known + rest


def _table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    """A Markdown table. With no rows it is a header alone, which is what "no runs" looks like."""
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def replace_block(readme: str, block: str) -> str:
    """Put the generated block between the markers in `README.md`, leaving the rest alone."""
    start, end = readme.find(BLOCK_START), readme.find(BLOCK_END)
    if start == -1 or end == -1 or end < start:
        raise ScoreboardError(
            f"README.md has no {BLOCK_START} ... {BLOCK_END} block for the scoreboard"
        )
    return readme[:start] + block + readme[end + len(BLOCK_END) :]


def comparable(text: str) -> str:
    """The text without the generation time, which changes on every run with no number changing."""
    return "\n".join(line for line in text.splitlines() if not line.startswith(GENERATED_PREFIX))


def _read(path: Path) -> str:
    """The file's text, or an empty string when it does not exist yet."""
    return path.read_text(encoding="utf-8") if path.is_file() else ""


def build_parser() -> argparse.ArgumentParser:
    """Describe the command."""
    parser = argparse.ArgumentParser(
        prog="python -m evals.scoreboard",
        description=(
            "Generate the scoreboard from the latest results file of each configuration. "
            "With --check, report whether the generated files are up to date and change nothing."
        ),
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when either generated file is out of date; write nothing",
    )
    parser.add_argument(
        "--results-dir",
        type=Path,
        default=RESULTS_DIR,
        help=f"where the results files are (default: {RESULTS_DIR})",
    )
    parser.add_argument(
        "--scoreboard",
        type=Path,
        default=SCOREBOARD_PATH,
        help=f"the scoreboard file to generate (default: {SCOREBOARD_PATH})",
    )
    parser.add_argument(
        "--readme",
        type=Path,
        default=README_PATH,
        help=f"the README whose scoreboard block to regenerate (default: {README_PATH})",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Generate both files, or check them, and say what happened."""
    args = build_parser().parse_args(argv)
    try:
        results = latest_per_config(args.results_dir)
    except ResultsError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return EXIT_ERROR

    generated_at = now_stamp()
    try:
        scoreboard = render(results, generated_at)
    except GoldenSetError as error:
        print(f"ERROR: {DEFAULT_GOLDEN_SET} failed validation:\n{error}", file=sys.stderr)
        return EXIT_ERROR
    readme_text = _read(args.readme)
    if not readme_text:
        print(f"ERROR: {args.readme} does not exist", file=sys.stderr)
        return EXIT_ERROR
    try:
        readme = replace_block(readme_text, render_readme_block(results, generated_at))
    except ScoreboardError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return EXIT_ERROR

    if args.check:
        return _check(args.scoreboard, scoreboard, args.readme, readme)

    args.scoreboard.parent.mkdir(parents=True, exist_ok=True)
    args.scoreboard.write_text(scoreboard, encoding="utf-8")
    args.readme.write_text(readme, encoding="utf-8")
    names = ", ".join(name for name, _ in _ordered(results)) or "no configurations"
    print(f"wrote {args.scoreboard}")
    print(f"updated the scoreboard block in {args.readme}")
    print(f"{len(results)} row(s) from the latest results per configuration: {names}")
    return EXIT_OK


def _check(scoreboard_path: Path, scoreboard: str, readme_path: Path, readme: str) -> int:
    """Compare both generated files with what is on disk, ignoring the generation time."""
    stale = []
    for path, generated in ((scoreboard_path, scoreboard), (readme_path, readme)):
        if comparable(_read(path)) != comparable(generated):
            stale.append(path)
            print(f"{path} is out of date")
        else:
            print(f"{path} is up to date")
    if stale:
        print("run: python -m evals.scoreboard", file=sys.stderr)
        return EXIT_STALE
    return EXIT_OK


if __name__ == "__main__":
    raise SystemExit(main())
